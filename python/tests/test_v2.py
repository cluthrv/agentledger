"""
v2 canonicalization and Merkle v2: byte-for-byte agreement with TypeScript.

fixtures/v2_vectors.json is generated by the TypeScript build
(fixtures/make_v2_vectors.js); fixtures/ts_v2_session.json is a session recorded
by the MCP demo gateway with v2 hashing.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path

import pytest

from agentledger import (
    MerkleProof,
    canonical_json,
    compute_merkle_root,
    compute_merkle_root_v2,
    generate_merkle_proof_v2,
    hash_action_record,
    hash_action_record_v2,
    hash_record_dict_v2,
    merkle_leaf_v2,
    merkle_node_v2,
    sha256,
    verify_exported_session,
    verify_merkle_proof_v2,
)

FIXTURES = Path(__file__).parent / "fixtures"
VECTORS = json.loads((FIXTURES / "v2_vectors.json").read_text(encoding="utf-8"))


def _load_session():
    return json.loads((FIXTURES / "ts_v2_session.json").read_text(encoding="utf-8"))


@pytest.mark.parametrize("case", VECTORS["canonical"], ids=lambda c: c["canonical"][:30])
def test_canonical_json_matches_typescript(case):
    assert canonical_json(case["value"]) == case["canonical"]


@pytest.mark.parametrize("case", VECTORS["records"], ids=lambda c: c["hash"][:12])
def test_record_hash_matches_typescript(case):
    assert hash_record_dict_v2(case["record"]) == case["hash"]


def test_nested_argument_change_is_detected():
    original, edited = VECTORS["records"][0], VECTORS["records"][1]
    assert original["record"]["input"]["args"]["amount"] == 2400000
    assert edited["record"]["input"]["args"]["amount"] == 240000
    assert original["hash"] != edited["hash"]


def test_v1_behavior_unchanged_nested_change_still_missed():
    r = VECTORS["records"][0]["record"]
    kwargs = dict(
        id=r["id"], session_id=r["sessionId"], sequence_number=r["sequenceNumber"],
        timestamp=r["timestamp"], agent_id=r["agentId"], action_type=r["actionType"],
        input=r["input"], output=r["output"], metadata=r["metadata"], previous_hash=r["previousHash"],
    )
    edited = copy.deepcopy(kwargs)
    edited["input"]["args"]["amount"] = 240000
    assert hash_action_record(**edited) == hash_action_record(**kwargs)
    assert hash_action_record_v2(**edited) != hash_action_record_v2(**kwargs)


@pytest.mark.parametrize("case", VECTORS["merkle"], ids=lambda c: f"n={len(c['hashes'])}")
def test_merkle_v2_matches_typescript(case):
    assert compute_merkle_root_v2(case["hashes"]) == case["root"]
    for i, ts_proof in enumerate(case["proofs"]):
        proof = generate_merkle_proof_v2(case["hashes"], i)
        assert proof.to_dict() == {k: ts_proof[k] for k in ("recordIndex", "recordHash", "siblings", "root")}
        assert verify_merkle_proof_v2(MerkleProof.from_dict(ts_proof))


def test_merkle_v2_structure():
    hs = [sha256(f"record-{i}") for i in range(3)]
    a, b, c = (merkle_leaf_v2(h) for h in hs)
    assert compute_merkle_root_v2(hs) == merkle_node_v2(merkle_node_v2(a, b), c)  # odd node carried up
    assert compute_merkle_root_v2([]) is None
    assert compute_merkle_root_v2(hs[:2]) != compute_merkle_root(hs[:2])
    with pytest.raises(ValueError):
        merkle_leaf_v2("not-hex")


def _checks(result):
    return {c.name: c.passed for c in result.checks}


def test_typescript_v2_session_verifies_in_python():
    doc = _load_session()
    assert doc["canonicalization"] == "v2" and doc["merkle"] == "v2"
    result = verify_exported_session(doc)
    assert result.valid, [c.to_dict() for c in result.checks]
    assert _checks(result)["anchored_root_match"] is True


def test_nested_arg_tamper_in_typescript_session_is_caught():
    doc = _load_session()
    rec = next(r for r in doc["records"] if r.get("metadata", {}).get("tool") == "create_credit_line")
    rec["input"]["args"]["amount"] = 240000
    result = verify_exported_session(doc)
    assert not result.valid
    assert _checks(result)["hash_chain_integrity"] is False


def test_downgrade_to_v1_fails():
    doc = _load_session()
    doc["canonicalization"] = "v1"
    doc["merkle"] = "v1"
    assert not verify_exported_session(doc).valid


def test_mixed_versions_fail():
    doc = _load_session()
    doc["merkle"] = "v1"
    result = verify_exported_session(doc)
    assert not result.valid
    assert _checks(result)["hash_version"] is False
